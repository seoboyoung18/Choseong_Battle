/*
 * 어디에도 넣지 않기로 한 말 — 왜 뺐는지 기억해 두려고 남긴다.
 *
 *   걸레   닦는 천. 집집마다 있는 물건이다
 *   새끼   동물의 아기. 사전이 낮춤 표시를 달아 둬서 출제는 자동으로 막힌다
 *   호구   호구조사·호구지책
 *   기생   기생충의 기생(寄生)
 *   내기   내기하다
 *   정사   정사(政事)·정사(正史)
 *   폭탄   물폭탄·폭탄세일
 *   미친   미친 듯이. 그 자체로는 흔한 말이다
 *
 * 동음이의어 하나 때문에 멀쩡한 낱말을 지우는 값이 훨씬 크다. 한 글자짜리도
 * 넣지 않는다 — 출제·판정 대상이 2~4글자뿐이라(FR-G1) 목록에만 남고 아무것도
 * 막지 못한다.
 */

/** 뜻풀이에 낮춤·비속 표시가 붙었는지 */
export function isDerogatory(definition) {
  if (!definition) return false;
  return DEROGATORY_MARKERS.some((mark) => definition.includes(mark));
}

/**
 * 두 목록을 words 테이블에 적용한다.
 *
 * 임포트할 때만이 아니라 따로도 돌 수 있어야 한다 — 목록에 한 줄 더할 때마다
 * 사전 27,000개를 다시 넣을 수는 없다.
 *
 * 목록에서 빠진 낱말은 되살린다. 기준이 바뀌었는데 예전 판정이 DB에 남아 있으면
 * 목록을 고쳐도 화면은 그대로다. 신고로 막은 낱말(source='REPORT')은 건드리지
 * 않는다 — 사람이 보고 막은 것을 목록이 되돌리면 안 된다.
 *
 * @param {{ query: Function }} db
 * @returns {Promise<{ banned: number, unserved: number, restored: number }>}
 */
export async function applyBlocklist(db) {
  const blocked = [...BLOCKED];

  // 1) 기준에서 빠진 낱말 되살리기 (사전에서 온 것만)
  const restored = await db.query(
    `UPDATE words SET status = 'ACTIVE'
      WHERE status = 'BANNED'
        AND source <> 'REPORT'
        AND NOT (text = ANY($1::text[]))`,
    [blocked],
  );

  // 2) 완전 차단
  const banned = await db.query(
    `UPDATE words SET status = 'BANNED', is_curated = false
      WHERE text = ANY($1::text[])
        AND status <> 'BANNED'`,
    [blocked],
  );

  // 3) 출제 금지 (판정은 그대로 인정)
  const unserved = await db.query(
    `UPDATE words SET is_curated = false
      WHERE text = ANY($1::text[])
        AND is_curated`,
    [[...NOT_SERVED]],
  );

  return {
    banned: banned.rowCount,
    unserved: unserved.rowCount,
    restored: restored.rowCount,
  };
}
