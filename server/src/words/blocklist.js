/** 뜻풀이에 낮춤·비속 표시가 붙었는지 */
export function isDerogatory(definition) {
  if (!definition) return false;
  return DEROGATORY_MARKERS.some((mark) => definition.includes(mark));
}

/**
 * 차단 목록을 words 테이블에 적용한다.
 *
 * 임포트할 때만이 아니라 따로도 돌 수 있어야 한다 — 목록에 한 줄 더할 때마다
 * 사전 27,000개를 다시 넣을 수는 없다.
 *
 * @param {{ query: Function }} db
 * @returns {Promise<{ banned: number }>}
 */
export async function applyBlocklist(db) {
  const { rowCount } = await db.query(
    `UPDATE words
        SET status = 'BANNED', is_curated = false
      WHERE text = ANY($1::text[])
        AND status <> 'BANNED'`,
    [[...BLOCKED]],
  );
  return { banned: rowCount };
}
